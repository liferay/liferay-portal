package com.liferay.portal.tools.schema.manifest.builder;

import com.liferay.petra.string.StringBundler;
import com.liferay.petra.string.StringUtil;
import com.liferay.portal.kernel.test.util.RandomTestUtil;

import java.io.File;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;

import java.time.Instant;

import java.util.regex.Matcher;
import java.util.regex.Pattern;

import org.junit.Assert;
import org.junit.Before;
import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;

/**
 * @author Luis Ortiz
 */
public class SchemaManifestBuilderTest {

	@Before
	public void setUp() {
		_baseDir = temporaryFolder.getRoot();

		_manifestFile = new File(
			_baseDir, "src/main/resources/META-INF/schema/manifest.json");
	}

	@Test
	public void testSchemaManifestBuilder() throws Exception {
		String module = RandomTestUtil.randomString();

		_writeBndFile(module);

		_buildSchemaManifest(null);

		String timestamp = _assertManifest(module);

		Instant.parse(timestamp);

		_writeManifest(
			StringUtil.replace(
				_read(_manifestFile), timestamp, "2000-01-01T00:00:00Z"));

		_buildSchemaManifest(null);

		Assert.assertEquals("2000-01-01T00:00:00Z", _assertManifest(module));

		_writeManifest("{}");

		_buildSchemaManifest(null);

		Assert.assertNotEquals("2000-01-01T00:00:00Z", _assertManifest(module));

		module = RandomTestUtil.randomString();

		_writeBndFile(module);

		_buildSchemaManifest(null);

		_assertManifest(module);
	}

	@Test
	public void testSchemaManifestBuilderWithModule() throws Exception {
		_writeBndFile(RandomTestUtil.randomString());

		String module = RandomTestUtil.randomString();

		_buildSchemaManifest(module);

		_assertManifest(module);
	}

	@Test(expected = IllegalArgumentException.class)
	public void testSchemaManifestBuilderWithoutBndFile() throws Exception {
		_buildSchemaManifest(null);
	}

	@Rule
	public TemporaryFolder temporaryFolder = new TemporaryFolder();

	private String _assertManifest(String module) throws Exception {
		String content = _read(_manifestFile);

		Matcher matcher = _timestampPattern.matcher(content);

		Assert.assertTrue(content, matcher.find());

		String timestamp = matcher.group(1);

		Assert.assertEquals(
			StringBundler.concat(
				"{\n\t\"description\": \"Database changes manifest of one ",
				"Liferay module, generated by Liferay Schema Manifest ",
				"Builder. Do not edit it by hand. Top-level keys: 'module' is ",
				"the module's Bundle-SymbolicName, or 'portal' for portal ",
				"core; 'timestamp' is when the content last changed.\",\n",
				"\t\"module\": \"", module, "\",\n\t\"timestamp\": \"",
				timestamp, "\"\n}"),
			content);

		return timestamp;
	}

	private void _buildSchemaManifest(String module) throws Exception {
		new SchemaManifestBuilder(
			_baseDir.getAbsolutePath(),
			"src/main/resources/META-INF/schema/manifest.json", module);
	}

	private String _read(File file) throws Exception {
		return new String(
			Files.readAllBytes(file.toPath()), StandardCharsets.UTF_8);
	}

	private void _writeBndFile(String bundleSymbolicName) throws Exception {
		File bndFile = new File(_baseDir, "bnd.bnd");

		String content = StringBundler.concat(
			"Bundle-Name: ", RandomTestUtil.randomString(),
			"\nBundle-SymbolicName: ", bundleSymbolicName, "\n");

		Files.write(bndFile.toPath(), content.getBytes(StandardCharsets.UTF_8));
	}

	private void _writeManifest(String content) throws Exception {
		Files.write(
			_manifestFile.toPath(), content.getBytes(StandardCharsets.UTF_8));
	}

	private static final Pattern _timestampPattern = Pattern.compile(
		"\"timestamp\": \"([^\"]*)\"");

	private File _baseDir;
	private File _manifestFile;

}