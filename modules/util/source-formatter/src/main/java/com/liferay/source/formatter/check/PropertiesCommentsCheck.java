package com.liferay.source.formatter.check;

import com.liferay.petra.string.CharPool;
import com.liferay.portal.kernel.util.StringUtil;
import com.liferay.source.formatter.check.util.SourceUtil;

import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * @author Peter Shin
 */
public class PropertiesCommentsCheck extends BaseFileCheck {

	@Override
	protected String doProcess(
		String fileName, String absolutePath, String content) {

		if (fileName.endsWith("/test.properties") &&
			!absolutePath.equals(
				SourceUtil.getRootDirName(absolutePath) + "/test.properties")) {

			content = _removeUnnecessaryComments(content);
		}

		content = _formatComments(content);

		return _wrapComments(content);
	}

	private String _formatComments(String content) {
		Matcher matcher = _commentPattern1.matcher(content);

		while (matcher.find()) {
			if ((matcher.group(1) != null) || (matcher.group(3) != null)) {
				continue;
			}

			String comment = matcher.group(2);

			String titleCaseComment = StringUtil.getTitleCase(
				comment, true, _BRAND_NAMES);

			titleCaseComment = titleCaseComment.replaceAll(
				"(?i)(\\A|\\s)sf(\\Z|\\s)", "$1Source Formatter$2");

			if (!titleCaseComment.equals(comment)) {
				return StringUtil.replaceFirst(
					content, comment, titleCaseComment, matcher.start(2));
			}
		}

		return content;
	}

	private String _removeUnnecessaryComments(String content) {
		Matcher matcher = _commentPattern2.matcher(content);

		if (matcher.find()) {
			return content.substring(matcher.end());
		}

		return content;
	}

	private String _splitComment(String comment, String prefix) {
		if (comment.length() <= getMaxLineLength()) {
			return comment;
		}

		int x = prefix.length() + 1;

		if (comment.startsWith(prefix + " See http")) {
			x += 4;
		}

		x = comment.indexOf(CharPool.SPACE, x);

		if (x == -1) {
			return comment;
		}

		if (x <= getMaxLineLength()) {
			x = comment.lastIndexOf(CharPool.SPACE, getMaxLineLength());
		}

		return comment.substring(0, x) + "\n" +
			_splitComment(prefix + " " + comment.substring(x + 1), prefix);
	}

	private String _wrapComments(String content) {
		Matcher matcher = _commentPattern3.matcher(content);

		while (matcher.find()) {
			String match = matcher.group();

			String prefix = matcher.group(1);

			String comment = _splitComment(
				StringUtil.removeSubstring(match, "\n" + prefix), prefix);

			if (!StringUtil.equals(match, comment)) {
				return StringUtil.replaceFirst(
					content, match, comment, matcher.start());
			}
		}

		return content;
	}

	private static final String[] _BRAND_NAMES = {
		"jQuery", "reCAPTCHA", "svg4everybody", "tc"
	};

	private static final Pattern _commentPattern1 = Pattern.compile(
		"([^#]\\s*)?\\n\\s*#+\\s+(\\w[\\s\\w]+)(\\n\\s*#+.*\\w+.*)?$",
		Pattern.MULTILINE);
	private static final Pattern _commentPattern2 = Pattern.compile(
		"\\A(##\n)*## DO NOT EDIT THIS FILE.*\n(##.*\n)*\n*");
	private static final Pattern _commentPattern3 = Pattern.compile(
		"^([ \t]*(?:#+|\\$h\\d+)) (?!Env: )\\S.*(\n\\1 (?!Env: )\\S.*)*",
		Pattern.MULTILINE);

}