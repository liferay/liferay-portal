import getExportedSymbols from './getExportedSymbols.mjs';

/**
 * Create an export bridge file that can be used by esbuild as an entry point.
 *
 * Export bridges are necessary since we need esbuild to export symbols using
 * standard ESM syntax and for that to happen it must be fed an ES module as
 * entry point. If fed a CommonJS one esbuild will refuse to export things as
 * ESM syntax.
 */
export default async function getExportBridgeJavaScript(
	overridenPackageSymbols,
	moduleName
) {
	const symbols = await getExportedSymbols(
		overridenPackageSymbols,
		moduleName
	);

	delete symbols.__esModule;

	const namedExportSymbols = Object.keys(symbols)
		.filter((symbol) => symbol !== 'default')
		.join(',\n');

	//
	// The symbol set already states whether a default export is needed:
	// packages generated by a harmony aware tool expose their own `default`,
	// and for CommonJS ones getExportedSymbols() infers it so that other
	// modules can find the exported object when they are interoperated by
	// tools like babel or webpack. Packages with overridden symbols get a
	// default export only when the override lists it.
	//
	// Note that we need to use import from instead of require in the generated
	// source because otherwise esbuild fails to honor "browser" field of
	// package.json files.
	//

	let source = `
export {${namedExportSymbols}} from '${moduleName}';
`;

	if (symbols.default) {
		source += `import __x__ from '${moduleName}';`;
		source += `export default __x__;`;
	}

	return source;
}
