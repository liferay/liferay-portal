@RunWith(Arquillian.class)
public class JournalEditDDMStructuresDisplayContextTest {

	@ClassRule
	@Rule
	public static final AggregateTestRule aggregateTestRule =
		new LiferayIntegrationTestRule();

	@Before
	public void setUp() throws Exception {
		_group = GroupTestUtil.addGroup();
	}

	@Test
	public void testIsAutogenerateDDMStructureKeyConfigured() throws Exception {
		try (CompanyConfigurationTemporarySwapper
				companyConfigurationTemporarySwapper =
					new CompanyConfigurationTemporarySwapper(
						TestPropsValues.getCompanyId(),
						JournalServiceConfiguration.class.getName(),
						HashMapDictionaryBuilder.<String, Object>put(
							"autogenerateDDMStructureKey", false
						).build())) {

			Assert.assertFalse(_isAutogenerateDDMStructureKey());
		}

		try (CompanyConfigurationTemporarySwapper
				companyConfigurationTemporarySwapper =
					new CompanyConfigurationTemporarySwapper(
						TestPropsValues.getCompanyId(),
						JournalServiceConfiguration.class.getName(),
						HashMapDictionaryBuilder.<String, Object>put(
							"autogenerateDDMStructureKey", true
						).build())) {

			Assert.assertTrue(_isAutogenerateDDMStructureKey());
		}
	}

	@Test
	@TestInfo("LPD-113664")
	public void testIsStructureKeyInputDisabled() throws Exception {
		DDMStructure ddmStructure = DDMStructureTestUtil.addStructure(
			_group.getGroupId(), JournalArticle.class.getName());

		try (CompanyConfigurationTemporarySwapper
				companyConfigurationTemporarySwapper =
					new CompanyConfigurationTemporarySwapper(
						TestPropsValues.getCompanyId(),
						JournalServiceConfiguration.class.getName(),
						HashMapDictionaryBuilder.<String, Object>put(
							"autogenerateDDMStructureKey", false
						).build())) {

			Assert.assertFalse(
				ReflectionTestUtil.<Boolean>invoke(
					_getJournalEditDDMStructuresDisplayContext(0),
					"isStructureKeyInputDisabled", new Class<?>[0]));

			Object journalEditDDMStructuresDisplayContext =
				_getJournalEditDDMStructuresDisplayContext(
					ddmStructure.getStructureId());

			Assert.assertFalse(
				ReflectionTestUtil.<Boolean>invoke(
					journalEditDDMStructuresDisplayContext,
					"isStructureKeyInputDisabled", new Class<?>[0]));

			Map<String, Object> dataEngineLayoutBuilderHandlerContext =
				ReflectionTestUtil.invoke(
					journalEditDDMStructuresDisplayContext,
					"getDataEngineLayoutBuilderHandlerContext",
					new Class<?>[0]);

			Assert.assertEquals(
				ddmStructure.getStructureKey(),
				dataEngineLayoutBuilderHandlerContext.get(
					"originalStructureKey"));
			Assert.assertEquals(
				Boolean.TRUE,
				dataEngineLayoutBuilderHandlerContext.get(
					"showStructureKeyChangesWarning"));
		}

		try (CompanyConfigurationTemporarySwapper
				companyConfigurationTemporarySwapper =
					new CompanyConfigurationTemporarySwapper(
						TestPropsValues.getCompanyId(),
						JournalServiceConfiguration.class.getName(),
						HashMapDictionaryBuilder.<String, Object>put(
							"autogenerateDDMStructureKey", true
						).build())) {

			Object journalEditDDMStructuresDisplayContext =
				_getJournalEditDDMStructuresDisplayContext(
					ddmStructure.getStructureId());

			Assert.assertTrue(
				ReflectionTestUtil.<Boolean>invoke(
					journalEditDDMStructuresDisplayContext,
					"isStructureKeyInputDisabled", new Class<?>[0]));

			Map<String, Object> dataEngineLayoutBuilderHandlerContext =
				ReflectionTestUtil.invoke(
					journalEditDDMStructuresDisplayContext,
					"getDataEngineLayoutBuilderHandlerContext",
					new Class<?>[0]);

			Assert.assertEquals(
				Boolean.FALSE,
				dataEngineLayoutBuilderHandlerContext.get(
					"showStructureKeyChangesWarning"));
		}
	}

	private Object _getJournalEditDDMStructuresDisplayContext(
			long ddmStructureId)
		throws Exception {

		MockLiferayPortletRenderRequest mockLiferayPortletRenderRequest =
			_getMockLiferayPortletRenderRequest();

		if (ddmStructureId > 0) {
			mockLiferayPortletRenderRequest.setParameter(
				"ddmStructureId", String.valueOf(ddmStructureId));
		}

		MVCPortlet mvcPortlet = (MVCPortlet)_portlet;

		mvcPortlet.render(
			mockLiferayPortletRenderRequest,
			new MockLiferayPortletRenderResponse());

		return mockLiferayPortletRenderRequest.getAttribute(
			"com.liferay.journal.web.internal.display.context." +
				"JournalEditDDMStructuresDisplayContext");
	}

	private MockLiferayPortletRenderRequest
			_getMockLiferayPortletRenderRequest()
		throws Exception {

		MockLiferayPortletRenderRequest mockLiferayPortletRenderRequest =
			new MockLiferayPortletRenderRequest();

		String path = "/edit_data_definition.jsp";

		mockLiferayPortletRenderRequest.setAttribute(
			MVCRenderConstants.
				PORTLET_CONTEXT_OVERRIDE_REQUEST_ATTIBUTE_NAME_PREFIX + path,
			new MockLiferayPortletContext(path));

		ThemeDisplay themeDisplay = new ThemeDisplay();

		themeDisplay.setCompany(
			_companyLocalService.getCompany(_group.getCompanyId()));
		themeDisplay.setLocale(LocaleUtil.getDefault());

		User user = UserTestUtil.getAdminUser(_group.getCompanyId());

		themeDisplay.setPermissionChecker(
			PermissionCheckerFactoryUtil.create(user));

		themeDisplay.setScopeGroupId(_group.getGroupId());
		themeDisplay.setUser(user);

		mockLiferayPortletRenderRequest.setAttribute(
			WebKeys.THEME_DISPLAY, themeDisplay);

		mockLiferayPortletRenderRequest.setParameter("mvcPath", path);

		return mockLiferayPortletRenderRequest;
	}

	private boolean _isAutogenerateDDMStructureKey() throws Exception {
		return ReflectionTestUtil.invoke(
			_getJournalEditDDMStructuresDisplayContext(0),
			"_isAutogenerateDDMStructureKey", new Class<?>[0]);
	}

	@Inject
	private CompanyLocalService _companyLocalService;

	@DeleteAfterTestRun
	private Group _group;

	@Inject(
		filter = "component.name=com.liferay.journal.web.internal.portlet.JournalPortlet"
	)
	private Portlet _portlet;

}