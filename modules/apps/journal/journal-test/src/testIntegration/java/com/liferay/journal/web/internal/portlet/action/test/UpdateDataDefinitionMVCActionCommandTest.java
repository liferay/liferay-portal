@RunWith(Arquillian.class)
public class UpdateDataDefinitionMVCActionCommandTest
	extends BaseDataDefinitionMVCActionCommandTestCase {

	public MVCActionCommand getMVCActionCommand() {
		return _mvcActionCommand;
	}

	@Test
	public void testProcessAction() throws Exception {
		_testProcessActionDataDefinitionValidationException();
		_testProcessActionDDMStructureValidationModelListenerException();
		_testProcessActionNestedFieldDefaultValue();
	}

	private DataDefinition _addDataDefinition(String dataDefinitionJSON)
		throws Exception {

		return DataDefinitionTestUtil.addDataDefinition(
			"journal", dataDefinitionResourceFactory, group.getGroupId(),
			dataDefinitionJSON, TestPropsValues.getUser());
	}

	private MockLiferayPortletActionRequest _processAction(
			DataDefinition dataDefinition, String dataDefinitionJSON,
			RecordingMockLiferayPortletActionResponse
				recordingMockLiferayPortletActionResponse)
		throws Exception {

		MockLiferayPortletActionRequest mockLiferayPortletActionRequest =
			createMockLiferayPortletActionRequest(
				null, null, dataDefinition.getId());

		mockLiferayPortletActionRequest.addParameter(
			"dataDefinition", dataDefinitionJSON);
		mockLiferayPortletActionRequest.addParameter(
			"dataLayout",
			String.valueOf(dataDefinition.getDefaultDataLayout()));
		mockLiferayPortletActionRequest.addParameter(
			"structureKey", RandomTestUtil.randomString());
		mockLiferayPortletActionRequest.addParameter(
			ActionRequest.ACTION_NAME, "/journal/update_data_definition");

		_portlet.processAction(
			mockLiferayPortletActionRequest,
			recordingMockLiferayPortletActionResponse);

		return mockLiferayPortletActionRequest;
	}

	private String _read(String fileName) throws Exception {
		return new String(
			FileUtil.getBytes(getClass(), "dependencies/" + fileName));
	}

	private void _testProcessActionDDMStructureValidationModelListenerException()
		throws Exception {

		String dataDefinitionJSON = _read(
			"data_definition_with_text_field.json");

		DataDefinition dataDefinition = _addDataDefinition(dataDefinitionJSON);

		RecordingMockLiferayPortletActionResponse
			recordingMockLiferayPortletActionResponse =
				new RecordingMockLiferayPortletActionResponse();

		try (CompanyConfigurationTemporarySwapper
				companyConfigurationTemporarySwapper =
					new CompanyConfigurationTemporarySwapper(
						TestPropsValues.getCompanyId(),
						JournalServiceConfiguration.class.getName(),
						MapUtil.singletonDictionary(
							"autogenerateDDMStructureKey", true))) {

			MockLiferayPortletActionRequest mockLiferayPortletActionRequest =
				_processAction(
					dataDefinition, dataDefinitionJSON,
					recordingMockLiferayPortletActionResponse);

			Assert.assertTrue(
				SessionErrors.contains(
					mockLiferayPortletActionRequest,
					"com.liferay.journal.web.internal.exception." +
						"DDMStructureValidationModelListenerException"));
			Assert.assertTrue(
				SessionMessages.contains(
					mockLiferayPortletActionRequest,
					portal.getPortletId(mockLiferayPortletActionRequest) +
						SessionMessages.KEY_SUFFIX_HIDE_DEFAULT_ERROR_MESSAGE));
		}

		Assert.assertNull(
			recordingMockLiferayPortletActionResponse.getRedirect());

		DDMStructure ddmStructure = _ddmStructureLocalService.getStructure(
			dataDefinition.getId());

		Assert.assertEquals(
			dataDefinition.getDataDefinitionKey(),
			ddmStructure.getStructureKey());
	}

	private void _testProcessActionDataDefinitionValidationException()
		throws Exception {

		String dataDefinitionJSON = _read(
			"data_definition_with_text_field.json");

		DataDefinition dataDefinition = _addDataDefinition(dataDefinitionJSON);

		DataDefinition invalidDataDefinition = DataDefinition.toDTO(
			dataDefinitionJSON);

		invalidDataDefinition.setName(Collections.emptyMap());

		RecordingMockLiferayPortletActionResponse
			recordingMockLiferayPortletActionResponse =
				new RecordingMockLiferayPortletActionResponse();

		MockLiferayPortletActionRequest mockLiferayPortletActionRequest =
			_processAction(
				dataDefinition, invalidDataDefinition.toString(),
				recordingMockLiferayPortletActionResponse);

		Assert.assertTrue(
			SessionErrors.contains(
				mockLiferayPortletActionRequest,
				DataDefinitionValidationException.MustSetValidName.class));
		Assert.assertFalse(
			SessionMessages.contains(
				mockLiferayPortletActionRequest,
				portal.getPortletId(mockLiferayPortletActionRequest) +
					SessionMessages.KEY_SUFFIX_HIDE_DEFAULT_ERROR_MESSAGE));

		Assert.assertNull(
			recordingMockLiferayPortletActionResponse.getRedirect());

		DDMStructure ddmStructure = _ddmStructureLocalService.getStructure(
			dataDefinition.getId());

		Assert.assertEquals(
			dataDefinition.getDataDefinitionKey(),
			ddmStructure.getStructureKey());
	}

	private void _testProcessActionNestedFieldDefaultValue() throws Exception {
		String dataDefinitionJSON = _read(
			"data_definition_with_nested_field.json");

		DataDefinition dataDefinition = _addDataDefinition(dataDefinitionJSON);

		DDMStructure ddmStructure = _ddmStructureLocalService.fetchDDMStructure(
			dataDefinition.getId());

		DDMForm ddmForm = ddmStructure.getDDMForm();

		Map<String, DDMFormField> ddmFormFieldsMap =
			ddmForm.getDDMFormFieldsMap(true);

		DDMFormField ddmFormField = ddmFormFieldsMap.get("Text");

		String predefinedValue = RandomTestUtil.randomString();

		ddmFormField.setPredefinedValue(
			new LocalizedValue() {
				{
					addString(LocaleUtil.US, predefinedValue);
				}
			});

		_ddmStructureLocalService.updateStructure(
			TestPropsValues.getUserId(), ddmStructure.getStructureId(), ddmForm,
			ddmStructure.getDDMFormLayout(),
			ServiceContextTestUtil.getServiceContext());

		MockLiferayPortletActionRequest mockLiferayPortletActionRequest =
			createMockLiferayPortletActionRequest(
				null, null, dataDefinition.getId());

		mockLiferayPortletActionRequest.addParameter(
			"dataDefinition", dataDefinitionJSON);
		mockLiferayPortletActionRequest.addParameter(
			"dataLayout",
			String.valueOf(dataDefinition.getDefaultDataLayout()));
		mockLiferayPortletActionRequest.addParameter(
			"structureKey", dataDefinition.getDataDefinitionKey());

		_mvcActionCommand.processAction(
			mockLiferayPortletActionRequest,
			new MockLiferayPortletActionResponse());

		DataDefinitionResource.Builder builder =
			dataDefinitionResourceFactory.create();

		DataDefinitionResource dataDefinitionResource = builder.user(
			TestPropsValues.getUser()
		).build();

		dataDefinition = dataDefinitionResource.getDataDefinition(
			dataDefinition.getId());

		DataDefinitionField[] dataDefinitionFields =
			dataDefinition.getDataDefinitionFields();

		Assert.assertEquals(
			dataDefinitionFields.toString(), 1, dataDefinitionFields.length);

		DataDefinitionField dataDefinitionField = dataDefinitionFields[0];

		DataDefinitionField[] nestedDataDefinitionFields =
			dataDefinitionField.getNestedDataDefinitionFields();

		Assert.assertEquals(
			nestedDataDefinitionFields.toString(), 1,
			nestedDataDefinitionFields.length);

		DataDefinitionField nestedDataDefinitionField =
			nestedDataDefinitionFields[0];

		Assert.assertEquals(
			predefinedValue,
			MapUtil.getString(
				nestedDataDefinitionField.getDefaultValue(), "en_US"));
	}

	@Inject
	private DDMStructureLocalService _ddmStructureLocalService;

	@Inject(filter = "mvc.command.name=/journal/update_data_definition")
	private MVCActionCommand _mvcActionCommand;

	@Inject(filter = "jakarta.portlet.name=" + JournalPortletKeys.JOURNAL)
	private Portlet _portlet;

	private static class RecordingMockLiferayPortletActionResponse
		extends MockLiferayPortletActionResponse {

		public String getRedirect() {
			return _redirect;
		}

		@Override
		public Map<String, String[]> getRenderParameterMap() {
			return _renderParameterMap;
		}

		@Override
		public void sendRedirect(String location) {
			_redirect = location;
		}

		@Override
		public void setRenderParameter(String name, String... values) {
			_renderParameterMap.put(name, values);
		}

		private String _redirect;
		private final Map<String, String[]> _renderParameterMap =
			new HashMap<>();

	}

}