/**
 * Rewrites `js/i18n/liferayMessages.ts` from the keys of `js/i18n/en.ts`:
 * one literal `Liferay.Language.get` call per key, because the language
 * filter substitutes literals only. Run it after any catalogue change:
 *
 *     node scripts/generate-liferay-messages.mjs && yarn format
 *
 * New keys must also reach the global Language.properties via buildLang;
 * the i18n jest suite fails while the catalogues disagree.
 */

import {promises} from 'fs';
import {dirname, join} from 'path';
import {fileURLToPath} from 'url';

const {readFile, writeFile} = promises;

const i18nDir = join(
	dirname(fileURLToPath(import.meta.url)),
	'../src/main/resources/META-INF/resources/js/i18n'
);

const source = await readFile(join(i18nDir, 'en.ts'), 'utf8');

const collator = new Intl.Collator('en', {numeric: true});

const keys = [...source.matchAll(/^\t'?([A-Za-z0-9:._-]+)'?:/gm)]
	.map(([, key]) => key)
	.sort(collator.compare);

const lines = keys.map((key) => `\t'${key}': Liferay.Language.get('${key}'),`);

await writeFile(
	join(i18nDir, 'liferayMessages.ts'),
	`/**
 * SPDX-FileCopyrightText: (c) 2026 Liferay, Inc. https://liferay.com
 * SPDX-License-Identifier: LGPL-2.1-or-later OR LicenseRef-Liferay-DXP-EULA-2.0.0-2023-06
 */

import {EditorMessages} from './index';

/**
 * Generated by scripts/generate-liferay-messages.mjs from en.ts; do not
 * edit by hand. The numeric ratio keys resolve to themselves by design.
 */
export const liferayMessages: EditorMessages = {
${lines.join('\n')}
};
`
);

process.stdout.write(`liferayMessages.ts written with ${keys.length} keys\n`);
