import com.liferay.portal.kernel.test.util.TestPropsValues;
import com.liferay.portal.test.rule.FeatureFlag;
import com.liferay.portal.test.rule.Inject;
import com.liferay.portal.test.rule.LiferayIntegrationTestRule;
import com.liferay.portal.test.rule.PermissionCheckerMethodTestRule;

import org.junit.Before;
import org.junit.ClassRule;
import org.junit.Rule;
import org.junit.Test;
import org.junit.runner.RunWith;

/**
 * @author Adolfo Pérez
 */
@RunWith(Arquillian.class)
public class LayoutBranchServiceTest {

	@ClassRule
	@Rule
	public static final AggregateTestRule aggregateTestRule =
		new AggregateTestRule(
			new LiferayIntegrationTestRule(),
			PermissionCheckerMethodTestRule.INSTANCE);

	@Before
	public void setUp() throws Exception {
		_group = GroupTestUtil.addGroup();
	}

	@FeatureFlag(enable = false, value = "LPD-105778")
	@Test
	public void testAddLayoutBranchWhenFeatureFlagDisabled() throws Exception {
		AssertUtils.assertFailure(
			UnsupportedOperationException.class,
			"Feature flag LPD-105778 is disabled for company " +
				TestPropsValues.getCompanyId(),
			() -> _layoutBranchService.addLayoutBranch(
				RandomTestUtil.randomLong(), RandomTestUtil.randomString(),
				RandomTestUtil.randomString(), false,
				ServiceContextTestUtil.getServiceContext(_group.getGroupId())));
	}

	@DeleteAfterTestRun
	private Group _group;

	@Inject
	private LayoutBranchService _layoutBranchService;

}