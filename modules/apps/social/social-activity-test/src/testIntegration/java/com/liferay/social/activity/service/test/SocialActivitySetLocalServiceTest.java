package com.liferay.social.activity.service.test;

import com.liferay.arquillian.extension.junit.bridge.junit.Arquillian;
import com.liferay.portal.kernel.dao.orm.QueryUtil;
import com.liferay.portal.kernel.model.Organization;
import com.liferay.portal.kernel.test.rule.AggregateTestRule;
import com.liferay.portal.kernel.test.rule.DeleteAfterTestRun;
import com.liferay.portal.kernel.test.util.OrganizationTestUtil;
import com.liferay.portal.test.rule.Inject;
import com.liferay.portal.test.rule.LiferayIntegrationTestRule;
import com.liferay.social.kernel.service.SocialActivitySetLocalService;

import java.util.Collections;

import org.junit.Assert;
import org.junit.ClassRule;
import org.junit.Rule;
import org.junit.Test;
import org.junit.runner.RunWith;

/**
 * @author Shuyang Zhou
 */
@RunWith(Arquillian.class)
public class SocialActivitySetLocalServiceTest {

	@ClassRule
	@Rule
	public static final AggregateTestRule aggregateTestRule =
		new LiferayIntegrationTestRule();

	@Test
	public void testGetOrganizationActivitySets() throws Exception {
		_organization = OrganizationTestUtil.addOrganization();

		Assert.assertEquals(
			Collections.emptyList(),
			_socialActivitySetLocalService.getOrganizationActivitySets(
				_organization.getOrganizationId(), QueryUtil.ALL_POS,
				QueryUtil.ALL_POS));
	}

	@DeleteAfterTestRun
	private Organization _organization;

	@Inject
	private SocialActivitySetLocalService _socialActivitySetLocalService;

}